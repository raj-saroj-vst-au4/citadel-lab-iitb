              backToTopBtn.classList.add('translate-y-0', 'opacity-100');
            } else {
              backToTopBtn.classList.add('translate-y-20', 'opacity-0');
              backToTopBtn.classList.remove('translate-y-0', 'opacity-100');
            }
          });

          // Scroll to top when clicked
          backToTopBtn.addEventListener('click', function () {
            window.scrollTo({
              top: 0,
              behavior: 'smooth'
            });
          });

          // Newsletter Form Submission
          const newsletterForm = document.getElementById('newsletterForm');
          const newsletterSuccess = document.getElementById('newsletterSuccess');

          if (newsletterForm) {
            newsletterForm.addEventListener('submit', function (e) {
              e.preventDefault();

              // Simulate form submission
              newsletterForm.classList.add('opacity-50', 'pointer-events-none');

              setTimeout(() => {
                newsletterForm.classList.add('hidden');
                newsletterSuccess.classList.remove('hidden');
              }, 1000);
            });
          }

          // Animated entrance for footer elements
          const footerSections = document.querySelectorAll('#footer .col-span-1, #footer .py-8, #footer .md\\:flex');

          const observer = new IntersectionObserver((entries) => {
            entries.forEach((entry) => {
              if (entry.isIntersecting) {
                setTimeout(() => {
                  entry.target.classList.add('opacity-100');
                  entry.target.classList.remove('translate-y-8');
                }, 100);
                observer.unobserve(entry.target);
              }
            });
          }, { threshold: 0.1 });

          footerSections.forEach((section, index) => {
            section.classList.add('opacity-0', 'translate-y-8', 'transition-all', 'duration-700', 'ease-out');
            section.style.transitionDelay = `${index * 150}ms`;
            observer.observe(section);
          });

          // Add smooth scrolling for all anchor links
          document.querySelectorAll('#footer a[href^="#"]').forEach(anchor => {
            anchor.addEventListener('click', function (e) {
              e.preventDefault();

              const targetId = this.getAttribute('href');
              if (targetId === '#') return;

              const targetElement = document.querySelector(targetId);
              if (targetElement) {
                targetElement.scrollIntoView({
                  behavior: 'smooth'
                });
              }
            });
          });
        });
